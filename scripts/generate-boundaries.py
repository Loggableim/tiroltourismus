def main():
    print("=== Writing Tirol Region Boundaries ===\n")
    
    ok = 0
    for slug, coords in BOUNDARIES.items():
        json_path = os.path.join(DATA_DIR, slug, 'index.json')
        if not os.path.exists(json_path):
            print(f"  ⏭  {slug}: not found")
            continue
        
        with open(json_path, 'r', encoding='utf-8') as f:
            entry = json.load(f)
        
        old_len = len(entry.get('grenzen', []))
        entry['grenzen'] = coords
        
        if not DRY_RUN:
            with open(json_path, 'w', encoding='utf-8') as f:
                json.dump(entry, f, indent=2, ensure_ascii=False)
                f.write('\n')
        
        print(f"  ✅ {slug}: {len(coords)} pts (was {old_len})")
        ok += 1
    
    print(f"\n✅ {ok}/13 regions updated")
    if DRY_RUN:
        print("🔷 DRY RUN")

if __name__ == '__main__':
    main()
